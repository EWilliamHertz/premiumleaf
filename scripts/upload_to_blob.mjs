#!/usr/bin/env node
import fs from 'fs';
import path from 'path';
import { put } from '@vercel/blob';

const ROOT = path.resolve(import.meta.dirname, '..');
const PUBLIC_CATALOG_DIR = path.join(ROOT, 'public', 'images', 'catalog');
const BLOB_MAP_FILE = path.join(ROOT, 'data', 'blob-urls.json');
const EXTRACTED_FILE = path.join(ROOT, 'data', 'chartogi_extracted.json');
const CATALOG_TS_FILE = path.join(ROOT, 'src', 'data', 'catalog.ts');

function loadEnvToken() {
  if (process.env.BLOB_READ_WRITE_TOKEN) {
    return process.env.BLOB_READ_WRITE_TOKEN.trim();
  }
  const envPath = path.join(ROOT, '.env.local');
  if (fs.existsSync(envPath)) {
    const lines = fs.readFileSync(envPath, 'utf8').splitlines?.() ?? fs.readFileSync(envPath, 'utf8').split(/\r?\n/);
    for (const line of lines) {
      const m = line.match(/^BLOB_READ_WRITE_TOKEN=(.+)$/);
      if (m) return m[1].trim().replace(/^["']|["']$/g, '');
    }
  }
  throw new Error('BLOB_READ_WRITE_TOKEN not found in env or .env.local');
}

function walkFiles(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walkFiles(full));
    else if (entry.isFile() && entry.name.endsWith('.webp')) out.push(full);
  }
  return out.sort();
}

async function uploadWithRetry(blobPath, buffer, token, attempt = 1) {
  try {
    return await put(blobPath, buffer, {
      access: 'public',
      addRandomSuffix: false,
      allowOverwrite: true,
      contentType: 'image/webp',
      cacheControlMaxAge: 60 * 60 * 24 * 365,
      token,
    });
  } catch (err) {
    if (attempt < 4) {
      await new Promise((r) => setTimeout(r, attempt * 1000));
      return uploadWithRetry(blobPath, buffer, token, attempt + 1);
    }
    throw err;
  }
}

async function main() {
  const token = loadEnvToken();
  const files = walkFiles(PUBLIC_CATALOG_DIR);
  console.log(`Found ${files.length} WebP images to upload to Vercel Blob...`);

  const existing = fs.existsSync(BLOB_MAP_FILE)
    ? JSON.parse(fs.readFileSync(BLOB_MAP_FILE, 'utf8'))
    : {};

  const force = process.argv.includes('--force');
  const mapping = { ...existing };

  const CONCURRENCY = 10;
  let index = 0;
  let uploaded = 0;

  async function worker() {
    while (index < files.length) {
      const myIdx = index++;
      const filePath = files[myIdx];
      const relFromPublic = '/' + path.relative(path.join(ROOT, 'public'), filePath).replace(/\\/g, '/');
      if (!force && mapping[relFromPublic] && mapping[relFromPublic].startsWith('https://')) {
        continue;
      }
      const blobKey = path.relative(path.join(ROOT, 'public', 'images'), filePath).replace(/\\/g, '/');
      const buf = fs.readFileSync(filePath);
      const res = await uploadWithRetry(blobKey, buf, token);
      mapping[relFromPublic] = res.url;
      uploaded++;
      if (uploaded % 25 === 0 || uploaded === files.length) {
        console.log(`Uploaded ${uploaded} / ${files.length} (latest: ${blobKey})`);
      }
    }
  }

  await Promise.all(Array.from({ length: CONCURRENCY }, () => worker()));
  fs.writeFileSync(BLOB_MAP_FILE, JSON.stringify(mapping, null, 2), 'utf8');

  // Rewrite image URLs in data/chartogi_extracted.json and src/data/catalog.ts
  const extracted = JSON.parse(fs.readFileSync(EXTRACTED_FILE, 'utf8'));
  const mapUrl = (u) => mapping[u] || u;

  for (const prod of extracted.products) {
    prod.heroImage = mapUrl(prod.heroImage);
    prod.dimensionImage = mapUrl(prod.dimensionImage);
    for (const v of prod.variants) {
      v.image = mapUrl(v.image);
    }
  }
  fs.writeFileSync(EXTRACTED_FILE, JSON.stringify(extracted, null, 2), 'utf8');

  // Preserve collections metadata from src/data/catalog.ts
  const currentCatalogTs = fs.readFileSync(CATALOG_TS_FILE, 'utf8');
  const colMatch = currentCatalogTs.match(/export const COLLECTIONS: CollectionMeta\[\] = (\[[\s\S]*?\]);/);
  if (!colMatch) throw new Error('Could not parse COLLECTIONS in src/data/catalog.ts');

  const nextCatalogTs =
    '// AUTO-GENERATED BY scripts/extract_catalog.py & scripts/upload_to_blob.mjs — DO NOT EDIT DIRECTLY.\n' +
    '// Runtime price/status edits from /admin are stored in data/catalog-overrides.json.\n' +
    "import type { Product, CollectionMeta } from '@/types/catalog';\n\n" +
    `export const COLLECTIONS: CollectionMeta[] = ${colMatch[1]};\n\n` +
    `export const BASE_PRODUCTS: Product[] = ${JSON.stringify(extracted.products, null, 2)};\n`;

  fs.writeFileSync(CATALOG_TS_FILE, nextCatalogTs, 'utf8');
  console.log(`Done! Uploaded ${uploaded} files, mapped ${Object.keys(mapping).length} total URLs to Vercel Blob.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
